void fb_draw_string(int x, int y, const char *s, uint32_t color) {
    while (*s) {
        char c = *s;
        if (c >= 32 && c < 127) {
            const uint8_t *glyph = font5x7[c - 32];
            for (int col = 0; col < 5; col++) {
                uint8_t bits = glyph[col];
                for (int row = 0; row < 7; row++) {
                    if (bits & (1 << row)) fb_draw_pixel(x + col, y + row, color);
                }
            }
        }
        x += 6; // Ширина символа + пробел
        s++;
    }
}

void fb_draw_u64(int x, int y, uint64_t v, uint32_t color) {
    char buf[21];
    int i = 20; buf[i] = 0;
    if (v == 0) buf[--i] = '0';
    else while (v && i > 0) { buf[--i] = (char)('0' + (v % 10)); v /= 10; }
    fb_draw_string(x, y, &buf[i], color);
}