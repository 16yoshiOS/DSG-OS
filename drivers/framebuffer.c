#include "drivers/framebuffer.h"
#include <stddef.h>

static fb_info_t s_fb;

int fb_init(uint32_t *pixels, uint32_t width, uint32_t height, uint32_t pitch) {
    if (!pixels) return -1;
    s_fb.pixels = pixels;
    s_fb.width  = width;
    s_fb.height = height;
    s_fb.pitch  = pitch;
    return 0;
}

fb_info_t *fb_get(void) { return &s_fb; }

void fb_draw_pixel(int x, int y, uint32_t color) {
    if (x < 0 || y < 0 || (uint32_t)x >= s_fb.width || (uint32_t)y >= s_fb.height)
        return;
    s_fb.pixels[(uint32_t)y * (s_fb.pitch / 4) + (uint32_t)x] = color;
}

void fb_fill_rect(int x, int y, int w, int h, uint32_t color) {
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++)
            fb_draw_pixel(x + i, y + j, color);
}

void fb_fill_round_rect(int x, int y, int w, int h, int r, uint32_t color) {
    if (r * 2 > w) r = w / 2;
    if (r * 2 > h) r = h / 2;
    fb_fill_rect(x + r, y, w - 2 * r, h, color);
    fb_fill_rect(x, y + r, r, h - 2 * r, color);
    fb_fill_rect(x + w - r, y + r, r, h - 2 * r, color);
    for (int dy = 0; dy < r; dy++) {
        for (int dx = 0; dx < r; dx++) {
            int ddx = r - dx - 1, ddy = r - dy - 1;
            if (ddx * ddx + ddy * ddy > r * r) continue;
            fb_draw_pixel(x + dx,             y + dy,             color);
            fb_draw_pixel(x + w - 1 - dx,     y + dy,             color);
            fb_draw_pixel(x + dx,             y + h - 1 - dy,     color);
            fb_draw_pixel(x + w - 1 - dx,     y + h - 1 - dy,     color);
        }
    }
}

